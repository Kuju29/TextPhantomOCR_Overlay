import assert from 'node:assert/strict';
import {createImageProgress, reduceImageProgress, mergeProgressDetail, publicImageProgress} from '../src/background/progress/image-progress-store.js';
let p=createImageProgress(1000);
p=reduceImageProgress(p,'scanning',{stage:'Preparing image'},1100);
p=reduceImageProgress(p,'lens_queued',{},1200);
p=reduceImageProgress(p,'lens',{queueWaitMs:75},1300);
p=reduceImageProgress(p,'grouping_queued',{},1800);
assert.equal(p.lens.state,'done');
assert.equal(p.lens.queueWaitMs,75);
p=reduceImageProgress(p,'grouping',{queueWaitMs:20},1820);
p=reduceImageProgress(p,'ai_queued',{},2000);
assert.equal(p.grouping.state,'done');
p=reduceImageProgress(p,'ai_generating',{queueWaitMs:240},2240);
p=mergeProgressDetail(p,{conversation:{phase:'translating',turn:4,pageCount:3,unitCount:42,queuedPageCount:2}},2300);
assert.match(p.ai.detail,/Conversation turn 4/);
assert.equal(p.ai.function,'preparing_request');
assert.equal(p.ai.pageCount,3);
assert.equal(p.ai.unitCount,42);
assert.equal(p.ai.queuedPageCount,2);
p=mergeProgressDetail(p,{phase:'sending_request'},2350);
assert.equal(p.ai.function,'sending_request');
p=mergeProgressDetail(p,{phase:'http_wait'},2400);
assert.equal(p.ai.function,'waiting_response');
p=mergeProgressDetail(p,{phase:'response_headers'},2450);
assert.equal(p.ai.function,'receiving_response');
p=mergeProgressDetail(p,{phase:'validating'},2500);
assert.equal(p.ai.function,'validating_result');
p=reduceImageProgress(p,'rendering',{},5000);
assert.equal(p.ai.state,'done');
p=reduceImageProgress(p,'done',{},5200);
const view=publicImageProgress(p,6000);
assert.equal(view.overall.state,'done');
assert.equal(view.insert.state,'done');
assert.equal(view.result.state,'done');
assert.ok(view.ai.elapsedMs>0);

let repair=createImageProgress(1000);
repair=reduceImageProgress(repair,'ai_generating',{},1200);
repair=mergeProgressDetail(repair,{repairPhase:'done'},5000);
const repaired=publicImageProgress(repair,6000);
assert.equal(repaired.overall.state,'done','terminal repair must stop Total instead of leaving RUN');
assert.equal(repaired.result.state,'done');

let q=createImageProgress(1000);
q=reduceImageProgress(q,'lens',{},1100);
q=reduceImageProgress(q,'ai_queued',{},1400);
assert.equal(q.grouping.state,'skipped','grouping must be visibly skipped when the pipeline did not need it');
q=reduceImageProgress(q,'error',{lastError:'provider timeout'},1800);
assert.equal(q.ai.state,'error');
assert.equal(q.result.state,'error');
assert.match(q.result.detail,/provider timeout/);
console.log('PASS per-image progress reducer tracks queue/running/done/skip/error lanes.');
